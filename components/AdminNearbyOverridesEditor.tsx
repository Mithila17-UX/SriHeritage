import { View, Text, StyleSheet, TouchableOpacity, ScrollView, Alert } from 'react-native';
import { Input } from './ui/input';
import { Label } from './ui/label';
import { Button } from './ui/button';
import { Card, CardContent } from './ui/card';
import { Badge } from './ui/badge';
import { databaseService, Site } from '../services/database';
import { computeNeighborsForSite } from '../utils/nearby';
import { formatKm } from '../utils/geo';

interface OverridesSectionData {
  include?: (string | number)[];
  exclude?: (string | number)[];
}

interface AdminNearbyOverridesEditorProps {
  currentSite: Site;
  allSites: Site[];
  overrides: {
    nearby?: OverridesSectionData;
    within?: OverridesSectionData;
  };
  onChange: (overrides: {
    nearby?: OverridesSectionData;
    within?: OverridesSectionData;
  }) => void;
  title: string; // "Within This Site (2 km)" or "Nearby Attractions (10 km)"
  category: 'within' | 'nearby';
  testID?: string;
}

export function AdminNearbyOverridesEditor({ 
  currentSite,
  allSites,
  overrides,
  onChange,
  title,
  category,
  testID
}: AdminNearbyOverridesEditorProps) {
  const [isExpanded, setIsExpanded] = useState(false);
  const [searchQuery, setSearchQuery] = useState('');
  const [searchResults, setSearchResults] = useState<Site[]>([]);
  const [isSearching, setIsSearching] = useState(false);

  // Get current overrides for this category
  const currentOverrides = overrides[category] || {};
  const includeList = currentOverrides.include || [];
  const excludeList = currentOverrides.exclude || [];

  // Compute the auto-generated list without overrides applied
  const thresholds = category === 'within' ? { nearbyKm: 10, withinKm: 2 } : { nearbyKm: 10, withinKm: 2 };
  const { within: autoWithin, nearby: autoNearby } = computeNeighborsForSite(
    allSites,
    currentSite.id,
    thresholds
  );
  const autoGenerated = category === 'within' ? autoWithin : autoNearby;

  // Compute final list with overrides applied
  const { within: finalWithin, nearby: finalNearby } = computeNeighborsForSite(
    allSites,
    currentSite.id,
    thresholds,
    overrides
  );
  const finalList = category === 'within' ? finalWithin : finalNearby;

  const handleSearch = async (query: string) => {
    if (!query.trim()) {
      setSearchResults([]);
      return;
    }

    setIsSearching(true);
    try {
      const sites = await databaseService.searchSites(query);
      
      // Filter out current site and sites already in include list
      const filteredSites = sites.filter(site => 
        site.id !== currentSite.id && 
        !includeList.includes(site.id)
      );
      
      setSearchResults(filteredSites);
    } catch (error) {
      console.error('Error searching sites:', error);
      Alert.alert('Error', 'Failed to search sites. Please try again.');
      setSearchResults([]);
    } finally {
      setIsSearching(false);
    }
  };

  const handleAddToInclude = (siteId: string | number) => {
    const newIncludeList = [...includeList, siteId];
    const newExcludeList = excludeList.filter(id => String(id) !== String(siteId));
    
    const newOverrides = {
      ...overrides,
      [category]: {
        include: newIncludeList,
        exclude: newExcludeList
      }
    };
    
    onChange(newOverrides);
    setSearchQuery('');
    setSearchResults([]);
  };

  const handleRemoveFromInclude = (siteId: string | number) => {
    const newIncludeList = includeList.filter(id => String(id) !== String(siteId));
    
    const newOverrides = {
      ...overrides,
      [category]: {
        ...currentOverrides,
        include: newIncludeList
      }
    };
    
    onChange(newOverrides);
  };

  const handleAddToExclude = (siteId: string | number) => {
    const newExcludeList = [...excludeList, siteId];
    const newIncludeList = includeList.filter(id => String(id) !== String(siteId));
    
    const newOverrides = {
      ...overrides,
      [category]: {
        include: newIncludeList,
        exclude: newExcludeList
      }
    };
    
    onChange(newOverrides);
  };

  const handleRemoveFromExclude = (siteId: string | number) => {
    const newExcludeList = excludeList.filter(id => String(id) !== String(siteId));
    
    const newOverrides = {
      ...overrides,
      [category]: {
        ...currentOverrides,
        exclude: newExcludeList
      }
    };
    
    onChange(newOverrides);
  };

  const getSiteById = (siteId: string | number): Site | null => {
    return allSites.find(site => String(site.id) === String(siteId)) || null;
  };

  const renderSiteRow = (relation: { siteId: string | number; airDistanceKm: number; roadDistanceKm?: number }, isAutoGenerated: boolean, isExcluded: boolean, isIncluded: boolean) => {
    const site = getSiteById(relation.siteId);
    if (!site) return null;

    return (
      <View key={String(relation.siteId)} style={[
        styles.siteRow,
        isExcluded && styles.excludedRow,
        isIncluded && styles.includedRow
      ]}>
        <View style={styles.siteInfo}>
          <Text style={styles.siteName}>{site.name}</Text>
          <Text style={styles.siteDetails}>
            {site.location} • {site.category}
          </Text>
          <View style={styles.badgeRow}>
            <Badge style={styles.distanceBadge}>
              <Text style={styles.badgeText}>{formatKm(relation.airDistanceKm)}</Text>
            </Badge>
            {relation.roadDistanceKm && (
              <Badge style={styles.roadDistanceBadge}>
                <Text style={styles.badgeText}>🛣️ {formatKm(relation.roadDistanceKm)}</Text>
              </Badge>
            )}
            {isAutoGenerated && (
              <Badge style={styles.autoGeneratedBadge}>
                <Text style={styles.badgeText}>Auto</Text>
              </Badge>
            )}
            {isIncluded && (
              <Badge style={styles.manuallyIncludedBadge}>
                <Text style={styles.badgeText}>Manual</Text>
              </Badge>
            )}
          </View>
        </View>
        
        <View style={styles.siteActions}>
          {isAutoGenerated && !isExcluded ? (
            <TouchableOpacity
              style={styles.excludeButton}
              onPress={() => handleAddToExclude(relation.siteId)}
            >
              <Text style={styles.excludeButtonText}>Exclude</Text>
            </TouchableOpacity>
          ) : isExcluded ? (
            <TouchableOpacity
              style={styles.includeButton}
              onPress={() => handleRemoveFromExclude(relation.siteId)}
            >
              <Text style={styles.includeButtonText}>Include</Text>
            </TouchableOpacity>
          ) : isIncluded ? (
            <TouchableOpacity
              style={styles.removeButton}
              onPress={() => handleRemoveFromInclude(relation.siteId)}
            >
              <Text style={styles.removeButtonText}>Remove</Text>
            </TouchableOpacity>
          ) : null}
        </View>
      </View>
    );
  };

  return (
    <View testID={testID}>
      <Card style={styles.container}>
        <TouchableOpacity 
          style={styles.header} 
          onPress={() => setIsExpanded(!isExpanded)}
          activeOpacity={0.7}
        >
          <View style={styles.headerContent}>
            <Text style={styles.title}>{title}</Text>
            <View style={styles.headerBadges}>
              <Badge style={styles.countBadge}>
                <Text style={styles.badgeText}>{finalList.length}</Text>
              </Badge>
              {excludeList.length > 0 && (
                <Badge style={styles.excludedCountBadge}>
                  <Text style={styles.badgeText}>-{excludeList.length}</Text>
                </Badge>
              )}
              {includeList.length > 0 && (
                <Badge style={styles.includedCountBadge}>
                  <Text style={styles.badgeText}>+{includeList.length}</Text>
                </Badge>
              )}
            </View>
          </View>
          <Text style={styles.expandIcon}>
            {isExpanded ? '▼' : '▶'}
          </Text>
        </TouchableOpacity>

        {isExpanded && (
          <CardContent style={styles.content}>
            {/* Search Section for Manual Includes */}
            <View style={styles.searchSection}>
              <Label style={styles.sectionLabel}>Manually Include Site</Label>
              <View style={styles.searchContainer}>
                <Input
                  placeholder="Search heritage sites to include..."
                  value={searchQuery}
                  onChangeText={(text) => {
                    setSearchQuery(text);
                    handleSearch(text);
                  }}
                  style={styles.searchInput}
                />
                {isSearching && (
                  <Text style={styles.searchingText}>🔍 Searching...</Text>
                )}
              </View>

              {/* Search Results */}
              {searchResults.length > 0 && (
                <>
                  <Text style={styles.searchResultsCount}>
                    {searchResults.length} site{searchResults.length !== 1 ? 's' : ''} found
                  </Text>
                  <ScrollView style={styles.searchResults} nestedScrollEnabled>
                    {searchResults.map((site) => (
                      <TouchableOpacity
                        key={site.id}
                        style={styles.searchResultItem}
                        onPress={() => handleAddToInclude(site.id)}
                      >
                        <View style={styles.searchResultContent}>
                          <Text style={styles.searchResultName}>{site.name}</Text>
                          <Text style={styles.searchResultDetails}>
                            {`${site.location || 'Unknown'} • ${site.category || 'Uncategorized'}`}
                          </Text>
                        </View>
                        <Text style={styles.addIcon}>+</Text>
                      </TouchableOpacity>
                    ))}
                  </ScrollView>
                </>
              )}
              
              {searchResults.length === 0 && !isSearching && searchQuery.trim() !== '' && (
                <View style={styles.emptySearchState}>
                  <Text style={styles.emptySearchText}>No matching sites found</Text>
                </View>
              )}
            </View>

            {/* Current Sites List */}
            <View style={styles.sitesSection}>
              <Label style={styles.sectionLabel}>
                Current List ({finalList.length} sites)
              </Label>
              
              {finalList.length === 0 ? (
                <View style={styles.emptyState}>
                  <Text style={styles.emptyStateText}>No sites in this category</Text>
                  <Text style={styles.emptyStateSubtext}>
                    Sites will be auto-computed based on distance thresholds
                  </Text>
                </View>
              ) : (
                <View style={styles.sitesList}>
                  {finalList.map((relation) => {
                    const isAutoGenerated = autoGenerated.some(auto => String(auto.siteId) === String(relation.siteId));
                    const isExcluded = excludeList.includes(relation.siteId);
                    const isIncluded = includeList.includes(relation.siteId);
                    
                    return renderSiteRow(relation, isAutoGenerated, isExcluded, isIncluded);
                  })}
                </View>
              )}
            </View>

            {/* Excluded Sites Section */}
            {excludeList.length > 0 && (
              <View style={styles.excludedSection}>
                <Label style={styles.sectionLabel}>
                  Excluded Sites ({excludeList.length})
                </Label>
                <View style={styles.sitesList}>
                  {excludeList.map((siteId) => {
                    const site = getSiteById(siteId);
                    if (!site) return null;
                    
                    return (
                      <View key={String(siteId)} style={[styles.siteRow, styles.excludedRow]}>
                        <View style={styles.siteInfo}>
                          <Text style={styles.siteName}>{site.name}</Text>
                          <Text style={styles.siteDetails}>
                            {site.location} • {site.category}
                          </Text>
                          <Badge style={styles.excludedBadge}>
                            <Text style={styles.badgeText}>Excluded</Text>
                          </Badge>
                        </View>
                        
                        <TouchableOpacity
                          style={styles.includeButton}
                          onPress={() => handleRemoveFromExclude(siteId)}
                        >
                          <Text style={styles.includeButtonText}>Include</Text>
                        </TouchableOpacity>
                      </View>
                    );
                  })}
                </View>
              </View>
            )}
          </CardContent>
        )}
      </Card>
    </View>
  );
}

